import re


# ============================================================
# LIMITS
# ============================================================

MAX_INPUT_LENGTH = 10_000
MAX_OUTPUT_LENGTH = 20_000


# ============================================================
# SECRET DETECTION
# ============================================================

SECRET_PATTERNS = [
    # Explicit secret assignments:
    # api_key=...
    # api-key: ...
    # secret_key=...
    # access_token=...
    re.compile(
        r"(?i)\b"
        r"(api[_-]?key|secret[_-]?key|access[_-]?token|"
        r"auth[_-]?token|private[_-]?key|client[_-]?secret)"
        r"\s*[:=]\s*"
        r"[A-Za-z0-9_\-./+=]{12,}"
    ),

    # Bearer tokens
    re.compile(
        r"(?i)\bbearer\s+"
        r"[A-Za-z0-9_\-./+=]{20,}"
    ),

    # OpenAI-style keys
    re.compile(
        r"\bsk-[A-Za-z0-9_-]{16,}\b"
    ),

    # Google API keys
    re.compile(
        r"\bAIza[A-Za-z0-9_-]{20,}\b"
    ),

    # Generic token assignments
    re.compile(
        r"(?i)\b(token|password|passwd|pwd)"
        r"\s*[:=]\s*"
        r"[^\s]{12,}"
    ),
]


# ============================================================
# PII PATTERNS
# ============================================================

EMAIL_PATTERN = re.compile(
    r"\b[A-Za-z0-9._%+-]+@"
    r"[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b"
)


PHONE_PATTERN = re.compile(
    r"(?<!\d)"
    r"(?:\+91[\s-]?)?"
    r"[6-9]\d{9}"
    r"(?!\d)"
)


AADHAAR_PATTERN = re.compile(
    r"(?<!\d)"
    r"\d{4}[\s-]?\d{4}[\s-]?\d{4}"
    r"(?!\d)"
)


# ============================================================
# INPUT VALIDATION
# ============================================================

def validate_input(text: str) -> tuple[bool, str]:
    """
    Validate user input BEFORE:
    - PostgreSQL storage
    - conversation memory
    - LLM processing
    """

    if not isinstance(text, str):
        return False, "Invalid input."

    text = text.strip()

    if not text:
        return False, "Please enter a message."

    if len(text) > MAX_INPUT_LENGTH:
        return False, (
            "Your message is too long. "
            "Please keep it under 10,000 characters."
        )

    # --------------------------------------------------------
    # SECRET DETECTION
    # --------------------------------------------------------

    for pattern in SECRET_PATTERNS:
        if pattern.search(text):
            return False, (
                "🔐 For your security, please don't send "
                "API keys, passwords, access tokens, or "
                "other secrets to SAK AI.\n\n"
                "I haven't processed or stored that message."
            )

    return True, text


# ============================================================
# PII SCRUBBING
# ============================================================

def scrub_pii(text: str) -> str:
    """
    Remove/redact sensitive personal information before
    putting conversation content into the LLM context.
    """

    text = EMAIL_PATTERN.sub(
        "[EMAIL_REDACTED]",
        text,
    )

    text = PHONE_PATTERN.sub(
        "[PHONE_REDACTED]",
        text,
    )

    text = AADHAAR_PATTERN.sub(
        "[ID_REDACTED]",
        text,
    )

    return text


# ============================================================
# OUTPUT VALIDATION
# ============================================================

def validate_output(text: str) -> str:
    """
    Sanitize model output before sending/storing it.
    """

    if not text:
        return (
            "I couldn't generate a response right now. "
            "Please try again."
        )

    text = text.strip()

    if len(text) > MAX_OUTPUT_LENGTH:
        text = text[:MAX_OUTPUT_LENGTH].rstrip()

    # Never allow secrets accidentally generated by the model
    for pattern in SECRET_PATTERNS:
        text = pattern.sub(
            "[SECRET_REDACTED]",
            text,
        )

    # Also scrub PII from model output.
    text = scrub_pii(text)

    return text